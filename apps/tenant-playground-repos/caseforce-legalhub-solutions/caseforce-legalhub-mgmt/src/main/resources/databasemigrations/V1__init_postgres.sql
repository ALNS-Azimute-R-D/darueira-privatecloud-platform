-- CaseForce LegalHub: PostgreSQL baseline (ADR-0018). It replaces the MySQL migrations V1..V8 and holds their final state:
-- the `tb_*` naming convention, with the column sizes of the old V7.

-- MySQL's `ON UPDATE CURRENT_TIMESTAMP` becomes a trigger, so rows keep their update time whoever writes them.
CREATE FUNCTION fn_set_ts_date_updated() RETURNS trigger AS
$$
BEGIN
    NEW.ts_date_updated = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE tb_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ds_email        VARCHAR(255) NOT NULL UNIQUE,
    ds_firstname    VARCHAR(255),
    ds_lastname     VARCHAR(255),
    ds_password     VARCHAR(255),
    is_enabled      BOOLEAN       DEFAULT TRUE,
    ts_date_created TIMESTAMPTZ   DEFAULT CURRENT_TIMESTAMP,
    ts_date_updated TIMESTAMPTZ   DEFAULT CURRENT_TIMESTAMP,
    ts_date_deleted TIMESTAMPTZ   NULL
);

CREATE TABLE tb_user_role (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ds_role         VARCHAR(50) NOT NULL,
    user_id         BIGINT      NOT NULL,
    ts_date_created TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES tb_user (id)
);
CREATE INDEX idx_user_role_user ON tb_user_role (user_id);

CREATE TABLE tb_permission_group (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ds_name         VARCHAR(255) NOT NULL,
    js_permissions  JSONB,
    ts_date_created TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    ts_date_updated TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tb_user_group (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    FOREIGN KEY (user_id) REFERENCES tb_user (id),
    FOREIGN KEY (group_id) REFERENCES tb_permission_group (id)
);
CREATE UNIQUE INDEX idx_user_group_unq ON tb_user_group (user_id, group_id);
CREATE INDEX idx_user_group_group ON tb_user_group (group_id);

CREATE TABLE tb_partner_agency (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ds_alias        VARCHAR(100) NOT NULL UNIQUE,
    ds_name         VARCHAR(255) NOT NULL,
    ds_email        VARCHAR(255),
    en_status       VARCHAR(50)  NOT NULL DEFAULT 'ACTIVE',
    ts_date_created TIMESTAMPTZ  DEFAULT CURRENT_TIMESTAMP,
    ts_date_updated TIMESTAMPTZ  DEFAULT CURRENT_TIMESTAMP,
    ts_date_deleted TIMESTAMPTZ  NULL
);

CREATE TABLE tb_legal_case (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ds_case_number    VARCHAR(100) NOT NULL UNIQUE,
    ds_legal_field    VARCHAR(100),
    en_status         VARCHAR(50)  NOT NULL DEFAULT 'OPEN',
    partner_agency_id BIGINT,
    lawyer_id         BIGINT,
    assignee_id       BIGINT,
    ts_date_created   TIMESTAMPTZ  DEFAULT CURRENT_TIMESTAMP,
    ts_date_updated   TIMESTAMPTZ  DEFAULT CURRENT_TIMESTAMP,
    ts_date_deleted   TIMESTAMPTZ  NULL,
    tx_summary        TEXT,
    FOREIGN KEY (lawyer_id) REFERENCES tb_user (id),
    FOREIGN KEY (assignee_id) REFERENCES tb_user (id),
    FOREIGN KEY (partner_agency_id) REFERENCES tb_partner_agency (id)
);
CREATE INDEX idx_legal_case_agency ON tb_legal_case (partner_agency_id);
CREATE INDEX idx_legal_case_lawyer ON tb_legal_case (lawyer_id);
CREATE INDEX idx_legal_case_assignee ON tb_legal_case (assignee_id);

CREATE TABLE tb_action (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ds_name         VARCHAR(255) NOT NULL,
    is_task         BOOLEAN      DEFAULT FALSE,
    en_status       VARCHAR(50)  NOT NULL DEFAULT 'OPEN',
    dt_due_date     DATE,
    legal_case_id   BIGINT       NOT NULL,
    assignee_id     BIGINT,
    created_by_id   BIGINT,
    ts_date_created TIMESTAMPTZ  DEFAULT CURRENT_TIMESTAMP,
    ts_date_updated TIMESTAMPTZ  DEFAULT CURRENT_TIMESTAMP,
    ts_date_deleted TIMESTAMPTZ  NULL,
    tx_notes        TEXT,
    FOREIGN KEY (legal_case_id) REFERENCES tb_legal_case (id),
    FOREIGN KEY (assignee_id) REFERENCES tb_user (id),
    FOREIGN KEY (created_by_id) REFERENCES tb_user (id)
);
CREATE INDEX idx_action_case ON tb_action (legal_case_id);
CREATE INDEX idx_action_assignee ON tb_action (assignee_id);
CREATE INDEX idx_action_created_by ON tb_action (created_by_id);

CREATE TABLE tb_webhook_subscription (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ds_target_url     VARCHAR(1024) NOT NULL,
    ds_secret         VARCHAR(255)  NOT NULL,
    en_status         VARCHAR(50)   NOT NULL DEFAULT 'ACTIVE',
    partner_agency_id BIGINT        NOT NULL,
    ts_date_created   TIMESTAMPTZ   DEFAULT CURRENT_TIMESTAMP,
    ts_date_updated   TIMESTAMPTZ   DEFAULT CURRENT_TIMESTAMP,
    ts_date_deleted   TIMESTAMPTZ   NULL,
    js_event_types    JSONB         NOT NULL,
    FOREIGN KEY (partner_agency_id) REFERENCES tb_partner_agency (id) ON DELETE CASCADE
);
CREATE INDEX idx_webhook_sub_agency ON tb_webhook_subscription (partner_agency_id, en_status);
CREATE INDEX idx_webhook_sub_deleted ON tb_webhook_subscription (ts_date_deleted);

CREATE TABLE tb_webhook_delivery (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ds_event_type           VARCHAR(50) NOT NULL,
    ds_entity_type          VARCHAR(50) NOT NULL,
    nr_entity_id            BIGINT      NOT NULL,
    en_status               VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    nr_response_status_code INT         NULL,
    nr_attempt_count        INT         NOT NULL DEFAULT 0,
    ts_last_attempt_at      TIMESTAMPTZ NULL,
    ts_date_created         TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    ts_date_updated         TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    subscription_id         BIGINT      NOT NULL,
    tx_response_body        TEXT        NULL,
    tx_error_message        TEXT        NULL,
    js_payload              JSONB       NOT NULL,
    FOREIGN KEY (subscription_id) REFERENCES tb_webhook_subscription (id) ON DELETE CASCADE
);
CREATE INDEX idx_webhook_deliv_sub ON tb_webhook_delivery (subscription_id);
CREATE INDEX idx_webhook_deliv_status_attempt ON tb_webhook_delivery (en_status, ts_last_attempt_at);
CREATE INDEX idx_webhook_deliv_created ON tb_webhook_delivery (ts_date_created);

CREATE TABLE tb_bulk_operation_job (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ds_job_type        VARCHAR(50) NOT NULL DEFAULT 'CASE_REASSIGNMENT',
    en_status          VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    nr_total_count     INT         NOT NULL DEFAULT 0,
    nr_processed_count INT         NOT NULL DEFAULT 0,
    nr_success_count   INT         NOT NULL DEFAULT 0,
    nr_failed_count    INT         NOT NULL DEFAULT 0,
    ts_date_created    TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    ts_date_updated    TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    requested_by_id    BIGINT      NOT NULL,
    target_lawyer_id   BIGINT      NOT NULL,
    js_filter_criteria JSONB       NOT NULL,
    js_error_summary   JSONB       NULL,
    FOREIGN KEY (requested_by_id) REFERENCES tb_user (id) ON DELETE CASCADE,
    FOREIGN KEY (target_lawyer_id) REFERENCES tb_user (id) ON DELETE CASCADE
);
CREATE INDEX idx_bulk_job_status ON tb_bulk_operation_job (en_status);
CREATE INDEX idx_bulk_job_user ON tb_bulk_operation_job (requested_by_id);
CREATE INDEX idx_bulk_job_target ON tb_bulk_operation_job (target_lawyer_id);

CREATE TRIGGER trg_tb_user_updated BEFORE UPDATE ON tb_user FOR EACH ROW EXECUTE FUNCTION fn_set_ts_date_updated();
CREATE TRIGGER trg_tb_permission_group_updated BEFORE UPDATE ON tb_permission_group FOR EACH ROW EXECUTE FUNCTION fn_set_ts_date_updated();
CREATE TRIGGER trg_tb_partner_agency_updated BEFORE UPDATE ON tb_partner_agency FOR EACH ROW EXECUTE FUNCTION fn_set_ts_date_updated();
CREATE TRIGGER trg_tb_legal_case_updated BEFORE UPDATE ON tb_legal_case FOR EACH ROW EXECUTE FUNCTION fn_set_ts_date_updated();
CREATE TRIGGER trg_tb_action_updated BEFORE UPDATE ON tb_action FOR EACH ROW EXECUTE FUNCTION fn_set_ts_date_updated();
CREATE TRIGGER trg_tb_webhook_subscription_updated BEFORE UPDATE ON tb_webhook_subscription FOR EACH ROW EXECUTE FUNCTION fn_set_ts_date_updated();
CREATE TRIGGER trg_tb_webhook_delivery_updated BEFORE UPDATE ON tb_webhook_delivery FOR EACH ROW EXECUTE FUNCTION fn_set_ts_date_updated();
CREATE TRIGGER trg_tb_bulk_operation_job_updated BEFORE UPDATE ON tb_bulk_operation_job FOR EACH ROW EXECUTE FUNCTION fn_set_ts_date_updated();
