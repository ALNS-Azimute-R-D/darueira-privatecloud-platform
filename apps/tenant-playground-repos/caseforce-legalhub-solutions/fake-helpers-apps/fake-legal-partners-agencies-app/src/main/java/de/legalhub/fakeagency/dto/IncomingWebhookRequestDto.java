package de.legalhub.fakeagency.dto;

import io.swagger.v3.oas.annotations.media.Schema;

@Schema(description = "DTO encapsulating an incoming webhook delivery request from CaseForce LegalHub")
public class IncomingWebhookRequestDto {

    @Schema(description = "Alias or ID identifier of the Partner Agency receiving this event", example = "berlin-legal-partners")
    private String agencyIdentifier;

    @Schema(description = "HMAC-SHA256 signature header value", example = "sha256=abcdef123456...")
    private String signatureHeader;

    @Schema(description = "Unix timestamp in milliseconds when signature was generated", example = "1724580000000")
    private Long timestamp;

    @Schema(description = "Unique delivery identifier generated by CaseForce", example = "del-12345")
    private String deliveryId;

    @Schema(description = "Event type name", example = "LEGAL_CASE_UPDATED")
    private String eventType;

    @Schema(description = "Raw JSON payload body")
    private String rawPayload;

    public IncomingWebhookRequestDto() {}

    public IncomingWebhookRequestDto(String agencyIdentifier, String signatureHeader, Long timestamp,
                                     String deliveryId, String eventType, String rawPayload) {
        this.agencyIdentifier = agencyIdentifier;
        this.signatureHeader = signatureHeader;
        this.timestamp = timestamp;
        this.deliveryId = deliveryId;
        this.eventType = eventType;
        this.rawPayload = rawPayload;
    }

    public String getAgencyIdentifier() {
        return agencyIdentifier;
    }

    public void setAgencyIdentifier(String agencyIdentifier) {
        this.agencyIdentifier = agencyIdentifier;
    }

    public String getSignatureHeader() {
        return signatureHeader;
    }

    public void setSignatureHeader(String signatureHeader) {
        this.signatureHeader = signatureHeader;
    }

    public Long getTimestamp() {
        return timestamp;
    }

    public void setTimestamp(Long timestamp) {
        this.timestamp = timestamp;
    }

    public String getDeliveryId() {
        return deliveryId;
    }

    public void setDeliveryId(String deliveryId) {
        this.deliveryId = deliveryId;
    }

    public String getEventType() {
        return eventType;
    }

    public void setEventType(String eventType) {
        this.eventType = eventType;
    }

    public String getRawPayload() {
        return rawPayload;
    }

    public void setRawPayload(String rawPayload) {
        this.rawPayload = rawPayload;
    }
}
